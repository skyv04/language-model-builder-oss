def fetch(version: str, name: str) -> str | None:
    url = f"https://cdn.jsdelivr.net/npm/lucide-static@{version}/icons/{name}.svg"
    request = urllib.request.Request(url, headers={"User-Agent": "lmb-linux-icon-builder"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return response.read().decode()
    except Exception:
        return None


def inner_markup(svg: str) -> str:
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
    return re.sub(r"\s+", " ", body).strip()


def main() -> None:
    version = sys.argv[1] if len(sys.argv) > 1 else "1.70.0"
    shapes: dict[str, str] = {}
    for key, candidates in ICONS.items():
        for name in candidates:
            svg = fetch(version, name)
            if svg:
                shapes[key] = inner_markup(svg)
                break
        else:
            raise SystemExit(f"no Lucide icon found for {key}: {candidates}")
    target = Path(__file__).resolve().parents[1] / "model_builder" / "ui" / "js" / "icons.js"
    target.write_text(
        f"// Generated by tools/build_icons.py from Lucide {version} (ISC license, see ui/licenses/Lucide-ISC.txt).\n"
        f"export const ICONS = {json.dumps(shapes, indent=0, sort_keys=True)};\n\n"
        "export function icon(name, size = 16, extraClass = \"\") {\n"
        "  const wrapper = document.createElement(\"span\");\n"
        "  wrapper.className = `icon ${extraClass}`.trim();\n"
        "  wrapper.innerHTML = `<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"${size}\" height=\"${size}\" viewBox=\"0 0 24 24\" "
        "fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\" stroke-linecap=\"round\" stroke-linejoin=\"round\" "
        "aria-hidden=\"true\">${ICONS[name] || ICONS.info}</svg>`;\n"
        "  return wrapper;\n"
        "}\n"
    )
    print(f"wrote {len(shapes)} icons to {target}")


if __name__ == "__main__":
    main()
